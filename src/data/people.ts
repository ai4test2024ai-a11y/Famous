export const PERSON_BY_ID: Map<string, Person> = new Map(PEOPLE.map((p) => [p.id, p]));

export function localizedName(p: Person, lang: "en" | "fa" | "ar"): string {
  if (lang === "fa" && p.fa) return p.fa;
  if (lang === "ar" && p.ar) return p.ar;
  return p.en;
}

/* Search index over every language variant — "مسی" and "Messi" hit the same ID */
export const SEARCH_INDEX: { p: Person; hay: string }[] = PEOPLE.map((p) => ({
  p,
  hay: `${p.en} ${p.fa} ${p.ar} ${p.id}`.toLowerCase(),
}));

export function searchPeople(q: string, limit = 60): Person[] {
  const s = q.trim().toLowerCase();
  if (!s) return [];
  const starts: Person[] = [];
  const contains: Person[] = [];
  for (const row of SEARCH_INDEX) {
    if (row.hay.startsWith(s)) starts.push(row.p);
    else if (row.hay.includes(s)) contains.push(row.p);
  }
  starts.sort((a, b) => b.pop - a.pop);
  contains.sort((a, b) => b.pop - a.pop);
  return [...starts, ...contains].slice(0, limit);
}

export function peopleByCat(cat: string): Person[] {
  if (cat === "iran") return PEOPLE.filter((p) => p.iran);
  if (cat === "world") return PEOPLE.filter((p) => p.pop >= 5);
  return PEOPLE.filter((p) => p.cat === cat);
}

export function yearOf(p: Person): number {
  return parseInt(p.dob.slice(0, 4), 10);
}

export function eraOf(p: Person): 1 | 2 | 3 | 4 | 5 {
  const y = yearOf(p);
  if (y < 1946) return 1;
  if (y < 1976) return 2;
  if (y < 1996) return 3;
  if (y < 2011) return 4;
  return 5;
}

export function rarityOf(p: Person): 1 | 2 | 3 | 4 {
  if (p.pop >= 5) return 4;
  if (p.pop >= 4) return 3;
  if (p.pop >= 3) return 2;
  return 1;
}
